if (!requireNamespace("DESeq2", quietly = TRUE)) stop("DESeq2 is REQUIRED for this integration job; skipping is not allowed.")
source("R/workflow.R")
d <- demo_inputs()
forward <- run_deseq2(d$counts, d$metadata, "adjacent", "tumor", TRUE)
reverse <- run_deseq2(d$counts, d$metadata, "tumor", "adjacent", TRUE)
aligned <- reverse[match(forward$gene_id, reverse$gene_id), ]
stopifnot(max(abs(forward$log2FoldChange + aligned$log2FoldChange), na.rm = TRUE) < 1e-4)
stopifnot(median(forward$log2FoldChange[forward$gene_id %in% rownames(d$counts)[1:12]], na.rm = TRUE) > 0)
m <- d$metadata; m$age <- c(41, 44, 39, 46, 50, 53, 48, 56, 60, 57, 62, 65)
adjusted <- run_deseq2(d$counts, m, "adjacent", "tumor", covariates = "age")
stopifnot(nrow(adjusted) > 0 && any(is.finite(adjusted$padj)))
dir.create("results/deseq2-ci", recursive = TRUE, showWarnings = FALSE)
write_tsv(forward, "results/deseq2-ci/paired_forward.tsv")
write_tsv(reverse, "results/deseq2-ci/paired_reverse.tsv")
write_tsv(adjusted, "results/deseq2-ci/age_adjusted.tsv")
writeLines(capture.output(sessionInfo()), "results/deseq2-ci/sessionInfo.txt")
cat("DESeq2 paired fit, reverse-contrast direction and age-adjusted fit passed\n")
