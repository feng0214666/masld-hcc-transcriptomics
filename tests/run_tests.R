source("R/workflow.R")
source("R/geo.R")
checks <- 0L
check <- function(ok) { stopifnot(ok); checks <<- checks + 1L }
fails <- function(expr) { result <- tryCatch({force(expr); FALSE}, error = function(e) TRUE); check(result) }
d <- demo_inputs(); x <- d$counts; m <- d$metadata
check(identical(x, demo_inputs()$counts))
check(identical(validate_inputs(x, m[12:1, ]), m[match(colnames(x), m$sample_id), ]))
bad <- x; bad[1, 1] <- NA; fails(validate_inputs(bad, m))
bad <- x; bad[1, 1] <- -1; fails(validate_inputs(bad, m))
bad <- x; bad[1, 1] <- 1.5; fails(validate_inputs(bad, m))
bad <- x; bad[, 1] <- 0; fails(validate_inputs(bad, m))
bad <- x; rownames(bad)[2] <- rownames(bad)[1]; fails(validate_inputs(bad, m))
bad <- m; bad$sample_id[2] <- bad$sample_id[1]; fails(validate_inputs(x, bad))
bad <- m; bad$sample_id[1] <- "UNKNOWN"; fails(validate_inputs(x, bad))
bad <- m; bad$group[1] <- NA; fails(validate_inputs(x, bad))
q <- qc_counts(x)
check(all(q$samples$library_size == colSums(x)))
check(abs(sum(q$variance$variance_fraction) - 1) < 1e-10)
check(nrow(q$pca) == ncol(x))
check(max(abs(q$logcpm - log2(sweep(x[q$keep, ], 2, colSums(x), "/") * 1e6 + 1))) < 1e-10)
s <- score_sets(q$logcpm, list(signal = rownames(x)[1:12], absent = "UNKNOWN"))
check(identical(s$coverage$scored, c(TRUE, FALSE)))
check(all(abs(tapply(s$scores$score, s$scores$program, mean)) < 1e-10))
check(mean(s$scores$score[m$group == "tumor"]) > mean(s$scores$score[m$group == "adjacent"]))
design <- make_design(m, "adjacent", "tumor", TRUE)
check(identical(deparse(design$formula), "~patient_id + group"))
fails(make_design(m[-1, ], "adjacent", "tumor", TRUE))
fails(make_design(m, "tumor", "tumor"))
fails(make_design(m, "missing", "tumor"))
bad <- m; bad$patient_id[1] <- NA; fails(make_design(bad, "adjacent", "tumor", TRUE))
check(identical(html_escape('<script>"x"&'), "&lt;script&gt;&quot;x&quot;&amp;"))
soft <- c("^SERIES = GSE1", "^SAMPLE = GSM1", "!Sample_title = First",
          "!Sample_organism_ch1 = Homo sapiens", "!Sample_characteristics_ch1 = sex: F",
          "!Sample_characteristics_ch1 = tissue: liver", "^SAMPLE = GSM2", "!Sample_title = Second")
parsed <- parse_geo_soft(soft)
check(identical(parsed$sample_id, c("GSM1", "GSM2")))
check(parsed$characteristics[1] == "sex: F | tissue: liver")
fails(parse_geo_soft("<html>Access denied</html>"))
pairs <- read.delim("data/metadata/GSE164441_pairs.tsv", colClasses = "character")
check(nrow(pairs) == 20 && length(unique(pairs$patient_id)) == 10)
check(all(table(pairs$patient_id, pairs$group) == 1L))
tmp <- tempfile(fileext = ".tsv")
write_tsv(data.frame(gene_id = rownames(x), x, check.names = FALSE), tmp)
check(isTRUE(all.equal(read_counts(tmp), x)))
writeLines(c("bad\tS1\tS2", "g1\t2\t3"), tmp)
fails(read_counts(tmp))
writeLines(c("gene_id\tS1\tS2", "g1\t2\tfoo"), tmp)
fails(read_counts(tmp))
unlink(tmp)
no_match <- score_sets(q$logcpm, list(none = "UNKNOWN"))
check(nrow(no_match$scores) == 0L && !no_match$coverage$scored)
if (requireNamespace("DESeq2", quietly = TRUE)) {
  de <- run_deseq2(x, m, "adjacent", "tumor", TRUE)
  check(nrow(de) > 0 && all(c("gene_id", "log2FoldChange", "padj") %in% names(de)))
  check(median(de$log2FoldChange[de$gene_id %in% rownames(x)[1:12]], na.rm = TRUE) > 0)
} else cat("SKIP: DESeq2 integration (optional package not installed)\n")
cat(checks, "checks passed\n")
